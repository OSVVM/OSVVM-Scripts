"""
Link glossary terms and abbreviations in ReST files generated by Ruff!.

The terms are read from :file:`Glossary.rst` (``.. glossary::``), the abbreviations from :file:`Abbreviations.rst`
(``.. abbreviations::``). In each section of a file, the first prose use of a term becomes a ``:term:`` reference, the
first use of an abbreviation an ``:acs:`` (or ``:acsp:``) reference.

Not linked: headings, directives and their content (except list tables), inline literals, roles, links, emphasis,
substitutions and field names.
"""
from argparse import ArgumentParser
from bisect   import bisect_right
from pathlib  import Path
from re       import compile as re_compile, escape, Match, MULTILINE, Pattern
from typing   import Iterable, Iterator


#: Phrases containing a term, which mean something else; they are matched like a term, but never linked.
UNLINKED_PHRASES = (
	"build summary", "build report", "build reports", "build index", "build directory", "package settings file",
	"package settings files", "test case settings file",
)

#: Directives whose content is prose.
PROSE_DIRECTIVES = ("list-table", )

HEADING_UNDERLINE = re_compile(r"([#*=\-^~\"])\1+")
DIRECTIVE =         re_compile(r"\.\. ([\w-]+)::")
EXCLUDED =          re_compile(
	r"``[^`]*?``"                       # inline literal
	r"|:[\w:+-]+:`[^`]*`"               # role
	r"|`[^`]*`_{0,2}"                   # link, interpreted text
	r"|\*\*[^*\n]*?\*\*"                # strong emphasis
	r"|\*[^*\s][^*\n]*?\*"              # emphasis
	r"|\|[^|\s][^|\n]*\|"               # substitution
	r"|^[ \t]*:[^:`\n]+:(?=[ \t]|$)",   # field name
	flags=MULTILINE
)


def ReadEntries(file: Path, directive: str) -> list[str]:
	"""
	Read the entries of a definition-list directive.

	:param file:      ReST file holding the directive.
	:param directive: Name of the directive, ``glossary`` or ``abbreviations``.
	:returns:         The entries' names, in the order of the file.
	"""
	entries = []
	inside = False
	for line in file.read_text(encoding="utf-8").splitlines():
		if line.startswith(f".. {directive}::"):
			inside = True
		elif inside and line != "" and not line.startswith(" "):
			inside = False
		elif inside and line.startswith("   ") and not line.startswith("    ") and not line.startswith("   :"):
			entries.append(line.strip())

	return entries


def Inflections(name: str) -> list[str]:
	"""
	Return the spellings of a term: the term, its plural and, for a verb ending in *e*, its past tense.

	Only the last word of a term is inflected.

	:param name: The term, like ``Test Case``.
	:returns:    The spellings, like ``Test Case`` and ``Test Cases``.
	"""
	if name.endswith("y"):
		plural = f"{name[:-1]}ies"
	elif name.endswith(("s", "x", "ch", "sh")):
		plural = f"{name}es"
	else:
		plural = f"{name}s"

	spellings = [name, plural]
	if name.endswith("e"):
		spellings.append(f"{name}d")

	return spellings


def CreatePattern(terms: Iterable[str], abbreviations: Iterable[str]) -> tuple[Pattern, dict[str, tuple[str, str]]]:
	"""
	Create one pattern matching all spellings of all terms and abbreviations, the longest spelling first.

	:param terms:         The glossary terms.
	:param abbreviations: The abbreviations.
	:returns:             The pattern, and a mapping from a spelling (terms lowercase) to its role and target. The role
	                      of an unlinked phrase is empty.
	"""
	targets = {}
	for phrase in UNLINKED_PHRASES:
		targets[phrase] = ("", "")
	for term in terms:
		for spelling in Inflections(term):
			targets.setdefault(spelling.lower(), ("term", term))

	abbreviationTargets = {}
	for abbreviation in abbreviations:
		for spelling in {abbreviation, abbreviation.upper()}:
			abbreviationTargets[spelling] = ("acs", abbreviation)
			abbreviationTargets[f"{spelling}s"] = ("acsp", abbreviation)

	termAlternatives = "|".join(escape(s) for s in sorted(targets, key=len, reverse=True))
	abbreviationAlternatives = "|".join(escape(s) for s in sorted(abbreviationTargets, key=len, reverse=True))
	pattern = re_compile(
		rf"(?<![\w-])(?:(?P<abbreviation>{abbreviationAlternatives})|(?i:(?P<term>{termAlternatives})))(?![\w-])"
	)
	targets.update(abbreviationTargets)

	return pattern, targets


def ProseLines(lines: list[str]) -> Iterator[tuple[int, bool]]:
	"""
	Yield the index of each line that may contain prose, and whether a new section starts before it.

	:param lines: The lines of a ReST file.
	:returns:     A generator of ``(line index, new section)`` pairs.
	"""
	skipIndent = -1
	newSection = True
	for index, line in enumerate(lines):
		stripped = line.lstrip()
		indent = len(line) - len(stripped)
		if skipIndent >= 0:
			if stripped == "" or indent > skipIndent:
				continue
			skipIndent = -1

		if stripped == "":
			continue
		elif HEADING_UNDERLINE.fullmatch(stripped):
			newSection = True
			continue
		elif index + 1 < len(lines) and HEADING_UNDERLINE.fullmatch(lines[index + 1].strip()):
			continue
		elif stripped.startswith(".."):
			if (match := DIRECTIVE.match(stripped)) is not None and match[1] not in PROSE_DIRECTIVES:
				skipIndent = indent
			continue

		yield index, newSection
		newSection = False


def LinkTerms(text: str, pattern: Pattern, targets: dict[str, tuple[str, str]]) -> str:
	"""
	Link the first use of each term and abbreviation per section.

	:param text:    Content of a ReST file.
	:param pattern: Pattern matching all spellings, see :func:`CreatePattern`.
	:param targets: Role and target of each spelling, see :func:`CreatePattern`.
	:returns:       The content with references.
	"""
	lines = text.split("\n")
	lineStarts = []
	offset = 0
	for line in lines:
		lineStarts.append(offset)
		offset += len(line) + 1

	excluded: dict[int, list[tuple[int, int]]] = {}
	for match in EXCLUDED.finditer(text):
		first = bisect_right(lineStarts, match.start()) - 1
		last = bisect_right(lineStarts, match.end()) - 1
		for index in range(first, last + 1):
			excluded.setdefault(index, []).append((match.start() - lineStarts[index], match.end() - lineStarts[index]))

	linked = set()
	for index, newSection in ProseLines(lines):
		if newSection:
			linked = set()

		lineExcluded = excluded.get(index, [])

		def Replace(match: Match) -> str:
			spelling = match[0]
			start, end = match.span()
			if any(start < spanEnd and end > spanStart for spanStart, spanEnd in lineExcluded):
				return spelling

			role, target = targets[spelling if match["abbreviation"] else spelling.lower()]
			if role == "" or target in linked:
				return spelling

			linked.add(target)
			if role == "term":
				return f":term:`{spelling}`" if spelling.lower() == target.lower() else f":term:`{spelling} <{target}>`"
			elif spelling in (target, f"{target}s"):
				return f":{role}:`{target}`"
			else:
				return f":{role}:`{spelling} <{target}>`"

		lines[index] = pattern.sub(Replace, lines[index])

	return "\n".join(lines)


def Main() -> None:
	"""Link the terms and abbreviations in the files given on the command line."""
	argumentParser = ArgumentParser(description="Link glossary terms and abbreviations in ReST files.")
	argumentParser.add_argument("--glossary",      type=Path, required=True, help="ReST file with the glossary.")
	argumentParser.add_argument("--abbreviations", type=Path, required=True, help="ReST file with the abbreviations.")
	argumentParser.add_argument("files",           type=Path, nargs="+",     help="ReST files to patch in place.")
	arguments = argumentParser.parse_args()

	terms = ReadEntries(arguments.glossary, "glossary")
	abbreviations = ReadEntries(arguments.abbreviations, "abbreviations")
	if len(terms) == 0 or len(abbreviations) == 0:
		argumentParser.error(f"No entries read: {len(terms)} terms, {len(abbreviations)} abbreviations.")

	pattern, targets = CreatePattern(terms, abbreviations)
	for file in arguments.files:
		file.write_text(LinkTerms(file.read_text(encoding="utf-8"), pattern, targets), encoding="utf-8")


if __name__ == "__main__":
	Main()
